//! Paquets Arch Linux / Manjaro (.pkg.tar.zst, .pkg.tar.xz) : lecture et écriture.
//! Arch Linux (pacman) package reader and writer.

use crate::compress::{self, Codec};
use crate::model::{Dependency, Family, Format, Metadata, Package, ScriptStyle, Scripts};
use crate::tarutil::{self, Sink, TarOpts};
use crate::tree::{Kind, Tree};
use crate::version;
use anyhow::{Context, Result};
use std::fs::File;
use std::io::{BufReader, BufWriter, Write};
use std::path::Path;

const CONTROL_FILES: &[&str] = &[".PKGINFO", ".BUILDINFO", ".MTREE", ".INSTALL", ".CHANGELOG"];

/// Lit les paires « clé = valeur » de .PKGINFO.
pub fn parse_pkginfo(text: &str) -> Vec<(String, String)> {
    text.lines()
        .filter(|l| !l.trim_start().starts_with('#'))
        .filter_map(|l| l.split_once(" = ").or_else(|| l.split_once('=')))
        .map(|(k, v)| (k.trim().to_string(), v.trim().to_string()))
        .collect()
}

fn all<'a>(f: &'a [(String, String)], k: &str) -> Vec<&'a str> {
    f.iter().filter(|(key, _)| key == k).map(|(_, v)| v.as_str()).collect()
}

fn one<'a>(f: &'a [(String, String)], k: &str) -> &'a str {
    f.iter().find(|(key, _)| key == k).map(|(_, v)| v.as_str()).unwrap_or("")
}

/// Lit un paquet pacman.
pub fn read(path: &Path) -> Result<Package> {
    let f = File::open(path).with_context(|| format!("ouverture de {}", path.display()))?;
    let mut dec = compress::auto_decoder(BufReader::with_capacity(256 * 1024, f))?;
    let mut tree = Tree::new()?;
    let (kept, special) = tarutil::read_tar_into(&mut dec, &mut tree, |p| {
        if CONTROL_FILES.contains(&p) { Sink::Keep } else { Sink::Tree }
    })?;
    let get = |n: &str| kept.iter().find(|(p, _)| p == n).map(|(_, d)| String::from_utf8_lossy(d).to_string());
    let info = get(".PKGINFO").context("fichier .PKGINFO manquant : ce n'est pas un paquet Arch")?;
    let f = parse_pkginfo(&info);
    let mut warnings = Vec::new();
    if special > 0 {
        warnings.push("warn.special_files".into());
    }
    for b in all(&f, "backup") {
        if let Some(e) = tree.entries.get_mut(b.trim_start_matches('/')) {
            e.config = true;
        }
    }
    let (epoch, ver, rel) = version::split_pacman_version(one(&f, "pkgver"));
    let parse = |k: &str| -> Vec<Dependency> { all(&f, k).into_iter().filter_map(Dependency::parse_any).collect() };
    let install = get(".INSTALL");
    let meta = Metadata {
        name: one(&f, "pkgname").to_string(),
        version: ver,
        release: rel,
        epoch,
        arch: version::canonical_arch(one(&f, "arch")),
        summary: one(&f, "pkgdesc").to_string(),
        description: String::new(),
        license: all(&f, "license").join(" AND "),
        url: one(&f, "url").to_string(),
        maintainer: one(&f, "packager").to_string(),
        section: all(&f, "group").first().map(|s| s.to_string()).unwrap_or_default(),
        depends: parse("depend"),
        provides: parse("provides"),
        conflicts: parse("conflict"),
        replaces: parse("replaces"),
        dep_family: Some(Family::Arch),
        scripts: Scripts {
            style: if install.is_some() { ScriptStyle::Arch } else { ScriptStyle::None },
            arch_install: install,
            ..Default::default()
        },
        origin_format: Some(Format::Arch),
    };
    Ok(Package { meta, tree, format: Format::Arch, warnings })
}

pub struct PacmanWriteOpts {
    pub depends: Vec<Dependency>,
    pub provides: Vec<Dependency>,
    pub conflicts: Vec<Dependency>,
    pub replaces: Vec<Dependency>,
    /// Contenu du fichier .INSTALL (déjà adapté).
    pub install: Option<String>,
}

fn dep_str(d: &Dependency) -> String {
    match (&d.op, &d.version) {
        (Some(op), Some(v)) => format!("{}{}{}", d.name, op.std(), v),
        _ => d.name.clone(),
    }
}

/// Texte de .PKGINFO.
pub fn pkginfo_text(meta: &Metadata, tree: &Tree, o: &PacmanWriteOpts, builddate: u64) -> String {
    let name = version::pacman_name(&meta.name);
    let (ver, rel) = version::pacman_version(meta);
    let full = match meta.epoch.filter(|e| *e > 0) {
        Some(e) => format!("{e}:{ver}-{rel}"),
        None => format!("{ver}-{rel}"),
    };
    let one_line = |s: &str| s.lines().map(str::trim).filter(|l| !l.is_empty()).collect::<Vec<_>>().join(" ");
    let mut s = String::new();
    s.push_str(&format!("# Generated by TAMGA {}\n", crate::TAMGA_VERSION));
    s.push_str(&format!("pkgname = {name}\n"));
    s.push_str(&format!("pkgbase = {name}\n"));
    s.push_str(&format!("pkgver = {full}\n"));
    let desc = one_line(&meta.summary);
    s.push_str(&format!("pkgdesc = {}\n", if desc.is_empty() { name.clone() } else { desc }));
    if !meta.url.trim().is_empty() {
        s.push_str(&format!("url = {}\n", one_line(&meta.url)));
    }
    s.push_str(&format!("builddate = {builddate}\n"));
    let packager = if meta.maintainer.trim().is_empty() { crate::DEFAULT_MAINTAINER.to_string() } else { one_line(&meta.maintainer) };
    s.push_str(&format!("packager = {packager}\n"));
    s.push_str(&format!("size = {}\n", tree.total_size()));
    s.push_str(&format!("arch = {}\n", version::pacman_arch(&meta.arch)));
    let lic = if meta.license.trim().is_empty() { "custom".to_string() } else { one_line(&meta.license) };
    s.push_str(&format!("license = {lic}\n"));
    for d in &o.replaces {
        s.push_str(&format!("replaces = {}\n", dep_str(d)));
    }
    for d in &o.conflicts {
        s.push_str(&format!("conflict = {}\n", dep_str(d)));
    }
    for d in &o.provides {
        s.push_str(&format!("provides = {}\n", dep_str(d)));
    }
    for (p, e) in tree.entries.iter() {
        if e.config && e.is_file() {
            s.push_str(&format!("backup = {p}\n"));
        }
    }
    for d in &o.depends {
        s.push_str(&format!("depend = {}\n", dep_str(d)));
    }
    s
}

/// Échappe un nom pour mtree (octal pour les caractères spéciaux).
fn mtree_escape(p: &str) -> String {
    let mut out = String::new();
    for b in p.bytes() {
        if b.is_ascii_graphic() && b != b'\\' && b != b'#' && b != b'=' {
            out.push(b as char);
        } else {
            out.push_str(&format!("\\{:03o}", b));
        }
    }
    out
}

/// Texte (non compressé) de .MTREE.
fn mtree_text(tree: &Tree, extra: &[(&str, &[u8], u64)]) -> String {
    use md5::{Digest as _, Md5};
    use sha2::Sha256;
    let mut s = String::from("#mtree\n/set type=file uid=0 gid=0 mode=644\n");
    for (name, data, mtime) in extra {
        s.push_str(&format!(
            "./{} time={}.0 size={} md5digest={} sha256digest={}\n",
            name,
            mtime,
            data.len(),
            hex::encode(Md5::digest(data)),
            hex::encode(Sha256::digest(data))
        ));
    }
    for (p, e) in tree.entries.iter() {
        let mut line = format!("./{} time={}.0", mtree_escape(p), e.mtime);
        if e.uid != 0 {
            line.push_str(&format!(" uid={}", e.uid));
        }
        if e.gid != 0 {
            line.push_str(&format!(" gid={}", e.gid));
        }
        match &e.kind {
            Kind::Dir => line.push_str(&format!(" mode={:o} type=dir", e.mode)),
            Kind::Symlink(t) => line.push_str(&format!(" mode=777 type=link link={}", mtree_escape(t))),
            Kind::File(b) => {
                if e.mode != 0o644 {
                    line.push_str(&format!(" mode={:o}", e.mode));
                }
                line.push_str(&format!(" size={} md5digest={} sha256digest={}", b.size, b.md5_hex(), b.sha256_hex()));
            }
        }
        s.push_str(&line);
        s.push('\n');
    }
    s
}

/// Écrit un paquet .pkg.tar.zst.
pub fn write(meta: &Metadata, tree: &Tree, o: &PacmanWriteOpts, out: &Path) -> Result<()> {
    let now = tarutil::now();
    let pkginfo = pkginfo_text(meta, tree, o, now);
    let mut extra: Vec<(&str, &[u8], u64)> = vec![(".PKGINFO", pkginfo.as_bytes(), now)];
    if let Some(i) = &o.install {
        extra.push((".INSTALL", i.as_bytes(), now));
    }
    let mtree = mtree_text(tree, &extra);
    let mut mtree_gz = Vec::new();
    {
        let mut e = compress::encoder(Codec::Gzip, &mut mtree_gz, Some(9))?;
        e.write_all(mtree.as_bytes())?;
        e.finish_box()?;
    }

    let file = File::create(out).with_context(|| format!("création de {}", out.display()))?;
    let enc = compress::encoder(Codec::Zstd, BufWriter::new(file), None)?;
    let mut b = tar::Builder::new(enc);
    tarutil::append_bytes(&mut b, ".PKGINFO", pkginfo.as_bytes(), 0o644, now)?;
    tarutil::append_bytes(&mut b, ".MTREE", &mtree_gz, 0o644, now)?;
    if let Some(i) = &o.install {
        tarutil::append_bytes(&mut b, ".INSTALL", i.as_bytes(), 0o644, now)?;
    }
    let opts = TarOpts { dot_prefix: false, root_entry: false, numeric_owner_fallback: true };
    for (p, e) in tree.entries.iter() {
        tarutil::append_entry(&mut b, tree, p, e, &opts)?;
    }
    let enc = b.into_inner()?;
    enc.finish_box()?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pkginfo_parse() {
        let f = parse_pkginfo("# c\npkgname = foo\npkgver = 1:2.0-3\ndepend = glibc>=2.34\ndepend = gtk3\n");
        assert_eq!(one(&f, "pkgname"), "foo");
        assert_eq!(all(&f, "depend").len(), 2);
        assert_eq!(mtree_escape("a b"), "a\\040b");
    }
}
